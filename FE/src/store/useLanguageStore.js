const useLanguageStore = create(
  persist(
    (set, get) => ({
      language: 'vi',
      setLanguage: (lang) => set({ language: lang === 'en' ? 'en' : 'vi' }),
      toggleLanguage: () => set({ language: get().language === 'vi' ? 'en' : 'vi' }),
      t: (key, fallback = '') => {
        const lang = get().language || 'vi';
        return translations[lang]?.[key] || translations.vi?.[key] || fallback || key;
      }
    }),
    {
      name: 'petshop_language',
      storage: safePersistStorage,
    }
  )
);

export default useLanguageStore;
